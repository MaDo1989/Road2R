ALTER PROCEDURE [dbo].[USP_Login_with_phone_number_Mobile]
(
    @CellPhone NVARCHAR(11)
)
AS
BEGIN
    SET NOCOUNT ON;

    -- משתמש לא קיים
    IF NOT EXISTS
    (
        SELECT 1
        FROM Volunteer
        WHERE CellPhone = @CellPhone
           OR CellPhone2 = @CellPhone
    )
    BEGIN
        SELECT
            404 AS ResponseStatus,
            'User not found' AS Message;

        RETURN;
    END

    -- משתמש לא פעיל
    IF EXISTS
    (
        SELECT 1
        FROM Volunteer
        WHERE (CellPhone = @CellPhone OR CellPhone2 = @CellPhone)
          AND IsActive = 0
    )
    BEGIN
        SELECT
            403 AS ResponseStatus,
            'User is inactive. Please contact administrator.' AS Message;

        RETURN;
    END

    -- הצלחה
    SELECT 
	   [Id]
      ,[DisplayName]
      ,[FirstNameH]
      ,[LastNameH]
      ,[CellPhone]
      ,[CellPhone2]
      ,[HomePhone]
      ,[Address]
      ,[Email]
      ,[JoinDate]
      ,[IsActive]
	  ,[BirthDate]
      ,[Gender]
	  ,[AvailableSeats]
	  ,[joinYear]
	  ,[NoOfDocumentedRides]
	  ,[No_of_Rides]
      ,[IsBooster]
      ,[IsBabyChair]
	,200 AS ResponseStatus
    FROM Volunteer
    WHERE (CellPhone = @CellPhone OR CellPhone2 = @CellPhone)
      AND IsActive = 1;
END

