    -- interfering with SELECT statements.
    SET NOCOUNT ON

    -- Insert statements for procedure here
     SELECT 
        ur.RidePatNum,
        ur.PatientName,
        ur.PatientCellPhone,
        ur.Origin,
        ur.Destination,
        ur.PickupTime,
        ur.IsAfterNoon,
        ur.Area,
